PALETTE_NAMES = list(PALETTES.keys())


def get_palette(name: str) -> Optional[List[RGBColor]]:
    """Return the palette color list for the given name, or None if 'none' / unknown."""
    pal = PALETTES.get(name)
    if not pal:
        return None
    return pal